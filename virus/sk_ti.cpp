// ---- Rings (one producer, one consumer) ------------------------------------------------------------------------
template <int N>
struct ByteRing {  // N a power of two
    std::atomic<uint32_t> head, tail;  // zero-initialised by calloc
    uint8_t buf[N];
    bool push(const uint8_t* d, int n) {  // all or nothing
        const uint32_t h = head.load(std::memory_order_relaxed), t = tail.load(std::memory_order_acquire);
        if (N - (h - t) < static_cast<uint32_t>(n)) return false;
        for (int i = 0; i < n; ++i) buf[(h + i) & (N - 1)] = d[i];
        head.store(h + n, std::memory_order_release);
        return true;
    }
    int size() const { return static_cast<int>(head.load(std::memory_order_acquire) - tail.load(std::memory_order_relaxed)); }
    uint8_t peek(int i) const { return buf[(tail.load(std::memory_order_relaxed) + i) & (N - 1)]; }
    void drop(int n) { tail.store(tail.load(std::memory_order_relaxed) + n, std::memory_order_release); }
};

