// ---- Values and texts ---------------------------------------------------------------------------------------
uint8_t rawOf(const Plugin* p, int i) { return p->raw[i].load(std::memory_order_relaxed); }

bool holds(const ti::Alias& a, int v) {
    switch (a.op) {
        case ti::kEq: return v == a.value;
        case ti::kNe: return v != a.value;
        case ti::kGe: return v >= a.value;
        case ti::kLe: return v <= a.value;
    }
    return false;
}

const ti::Meaning& meaning(const Plugin* p, int i) {  // what parameter i means in the current modes
    const ti::Param& t = ti::kParams[i];
    for (int a = 0; a < t.numAliases; ++a)
        if (holds(t.aliases[a], rawOf(p, t.aliases[a].sel))) return t.aliases[a].m;
    return t.base;
}

uint32_t nameSignature(const Plugin* p) {  // changes whenever a mode selector moves a knob to another meaning
    uint32_t sig = 0;
    for (int i = 0; i < kNumVirus; ++i) {
        const ti::Param& t = ti::kParams[i];
        if (!t.numAliases) continue;
        const ti::Meaning* m = &meaning(p, i);
        sig = sig * 31u + static_cast<uint32_t>(m - &t.base) + 1u;
    }
    return sig;
}

uint8_t clampRaw(const ti::Meaning& m, int v) { return static_cast<uint8_t>(v < m.min ? m.min : v > m.max ? m.max : v); }

void valueText(const Plugin* p, int i, char* out, size_t len) {
    const ti::Meaning& m = meaning(p, i);
    const int v = clampRaw(m, rawOf(p, i));
    const ti::List& l = ti::kLists[m.list];
    if (l.count) std::snprintf(out, len, "%s", l.items[v < l.count ? v : l.count - 1]);
    else std::snprintf(out, len, "%d", v);
}

void patchName(const Plugin* p, char* out) {  // 10 characters at page B 112..121
    int n = 0;
    for (int k = 0; k < 10; ++k) {
        const uint8_t c = p->image[128 + 112 + k].load(std::memory_order_relaxed);
        out[n++] = c >= 32 && c < 127 ? static_cast<char>(c) : ' ';
    }
    while (n > 0 && out[n - 1] == ' ') --n;
    out[n] = 0;
}

void bankName(int b, char* out, size_t len) {  // sysex bank b + 1: the TI's RAM banks are A-D
    if (b < 26) std::snprintf(out, len, "Bank %c", 'A' + b);
    else std::snprintf(out, len, "Bank %d", b + 1);
}

uint8_t targetPart(const Plugin* p) {  // the edit buffer the plugin edits: Single, or a part of a Multi
    const int part = p->ctl[kPart].load(std::memory_order_relaxed);
    return part == 0 ? kPartSingle : static_cast<uint8_t>(part - 1);
}

