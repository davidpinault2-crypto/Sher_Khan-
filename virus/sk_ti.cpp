extern "C" __attribute__((visibility("default"))) void* VSTPluginMain(void* hostCallback) {
    void* mem = std::calloc(1, sizeof(Plugin));  // zero: every atomic, ring and flag starts at 0
    if (!mem) return nullptr;
    Plugin* p = static_cast<Plugin*>(mem);
    p->master = reinterpret_cast<audioMasterCallback>(hostCallback);
    p->fd.store(-1, std::memory_order_relaxed);
    p->ctlFd = -1;
    p->testFd = -1;
    const char* test = std::getenv("SKTI_TEST_FD");  // the host test's fake Virus: one end of a socket pair
    if (test && *test) p->testFd = ::dup(parseInt(test));
    if (p->testFd >= 0) ::fcntl(p->testFd, F_SETFL, O_NONBLOCK);
    for (int i = 0; i < kNumVirus; ++i) {
        const ti::Param& t = ti::kParams[i];
        p->raw[i].store(t.def, std::memory_order_relaxed);
        const int off = imageOffset(t.page);
        if (off >= 0) p->image[off + t.index].store(t.def, std::memory_order_relaxed);
    }
    p->ctl[kNotes].store(1, std::memory_order_relaxed);
    p->ctl[kAutoSend].store(1, std::memory_order_relaxed);
    const uint32_t now = nowMs();
    for (int i = 0; i < kNumVst; ++i) {
        p->sent[i].store(-1.f, std::memory_order_relaxed);
        p->pressFrame[i].store(0u - 2 * kDebounceFrames, std::memory_order_relaxed);
        p->pressMs[i].store(now - 2 * kDebounceMs, std::memory_order_relaxed);
    }
    p->nameSig.store(nameSignature(p), std::memory_order_relaxed);
    setStatus(p, kStSearching);
    p->updateDisplay.store(false, std::memory_order_relaxed);
    AEffect& e = p->fx;
    e.magic = kVstMagic;
    e.dispatcher = dispatcher;
    e.process = processAccumulating;
    e.setParameter = setParameter;
    e.getParameter = getParameter;
    e.processReplacing = processReplacing;
    e.numPrograms = 1;
    e.numParams = kNumVst;
    e.numInputs = 0;
    e.numOutputs = 2;
    e.flags = effFlagsCanReplacing | effFlagsProgramChunks | effFlagsIsSynth;
    e.ioRatio = 1.f;
    e.object = p;
    e.uniqueID = kUniqueId;
    e.version = kVersion;
    p->threadStarted = pthread_create(&p->thread, nullptr, ioThread, p) == 0;
    return &e;
}
