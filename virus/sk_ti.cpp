// SK TI Link: an Access Virus TI / TI2 over USB, from the plugin host built into MPC OS standalone (Akai Force,
// MPC Live/One/X/Key). A VST2 instrument that drives the synth itself; it makes no sound of its own.
//
// What travels over USB is MIDI only. Linux, which MPC OS runs on, has a driver for the TI's USB MIDI (snd-usb-audio,
// USB ID 133e:0815, two ports: "<name> MIDI" = the TI's MIDI DIN sockets, "<name> Synth" = the synth). Its USB audio
// is a protocol of Access's own that no Linux driver speaks: the sound comes back through the TI's analog outputs into
// the MPC's inputs.
//
// What the plugin does with the synth:
// - every parameter of a Single (oscillators, filters, envelopes, LFOs, modulation slots, effects, arpeggiator and
//   its pattern, ...): 373 VST parameters, on 15 pages and the Q-Links, sent as Virus SysEx parameter changes as you
//   turn them, and with mode-dependent names where the TI reuses a byte (HyperSaw, Wavetable, vocoder, tape delay,...);
// - READ the TI's edit buffer, SEND the plugin's patch to it, LOAD a program from the TI's banks, STORE into one;
// - the patch is saved with the MPC project and sent back to the TI when the project opens (AutoSend);
// - notes, controllers, pitch bend and pressure from the track go to the TI on the chosen MIDI channel; PANIC;
// - Single mode or one of the 16 parts of a Multi; the TI's global EQ / arpeggiator / delay / reverb switches,
//   master volume and tune;
// - changes made on the TI's panel come back to the knobs when the TI reports them (SysEx or controllers).
//
// How it reaches the synth: through the kernel's ALSA sequencer (/dev/snd/seq), as a client of its own connected to
// the TI's "Synth" port, so MPC can keep using the TI as a MIDI device at the same time. If the sequencer can't
// connect, it opens the TI's raw MIDI device instead. Both are spoken with plain system calls: the .so needs libc and
// libm only (no libasound), checked by virus/mpc/build.sh.
//
// Threads: the host's audio thread runs process and processEvents (notes go out from there, at the start of each
// block); its UI thread runs the dispatcher; one thread of our own connects, receives, and sends SysEx at a pace the
// TI's USB link keeps up with. Nothing locks: values are atomics, the queues are single-producer rings.
//
// The parameter table (virus/ti_table.h) is generated by virus/gen.py from virus/data/ti_params.json, which was
// derived from gearmulator's Virus TI parameter descriptions (GPL-3.0); this plugin is GPL-3.0 as well.
