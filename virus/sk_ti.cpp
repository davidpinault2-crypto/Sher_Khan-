// Number parsing by hand: with glibc >= 2.38 headers, strtol and sscanf become __isoc23_* symbols that the glibc
// of MPC OS before 3.10.1 doesn't have.
int parseInt(const char* s) {
    int v = 0;
    for (; *s >= '0' && *s <= '9' && v < 100000; ++s) v = v * 10 + (*s - '0');
    return v;
}

int hexDigit(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

