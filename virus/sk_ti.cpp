// One complete MIDI message (a channel message or a whole SysEx) to the TI. Returns false if it didn't go out.
bool sendMessage(Plugin* p, const uint8_t* m, int n) {
    const int fd = p->fd.load(std::memory_order_acquire);
    if (fd < 0 || n <= 0) return false;
    const uint8_t link = p->link.load(std::memory_order_relaxed);
    if (link != kSeq) {
        const ssize_t w = ::write(fd, m, static_cast<size_t>(n));
        return w == n;
    }
    uint8_t buf[sizeof(seq::Event) + 600];
    if (n > 600) return false;
    seq::Event ev;
    std::memset(&ev, 0, sizeof ev);
    ev.queue = seq::kQueueDirect;
    ev.source.client = p->myClient.load(std::memory_order_relaxed);
    ev.source.port = p->myPort.load(std::memory_order_relaxed);
    ev.dest.client = seq::kAddressSubscribers;
    size_t total = sizeof ev;
    const uint8_t st = m[0] & 0xf0, ch = m[0] & 0x0f;
    if (m[0] == 0xf0) {
        ev.type = seq::kSysex;
        ev.flags = seq::kLengthVariable;
        ev.data.ext.len = static_cast<unsigned int>(n);
        std::memcpy(buf + sizeof ev, m, static_cast<size_t>(n));
        total += static_cast<size_t>(n);
    } else if ((st == 0x90 || st == 0x80 || st == 0xa0) && n >= 3) {
        ev.type = st == 0x90 ? (m[2] ? seq::kNoteOn : seq::kNoteOff) : st == 0x80 ? seq::kNoteOff : seq::kKeyPress;
        ev.data.note.channel = ch;
        ev.data.note.note = m[1];
        ev.data.note.velocity = m[2];
    } else if (st == 0xb0 && n >= 3) {
        ev.type = seq::kController;
        ev.data.control.channel = ch;
        ev.data.control.param = m[1];
        ev.data.control.value = m[2];
    } else if (st == 0xc0 || st == 0xd0) {
        ev.type = st == 0xc0 ? seq::kPgmChange : seq::kChanPress;
        ev.data.control.channel = ch;
        ev.data.control.value = m[1];
    } else if (st == 0xe0 && n >= 3) {
        ev.type = seq::kPitchBend;
        ev.data.control.channel = ch;
        ev.data.control.value = ((m[2] << 7) | m[1]) - 8192;
    } else {
        return true;  // nothing else is sent
    }
    std::memcpy(buf, &ev, sizeof ev);
    return ::write(fd, buf, total) == static_cast<ssize_t>(total);
}

// A channel message from the audio thread: straight out on the sequencer (whole events, atomic per write), via the
// I/O thread's ring on a raw link (so it can't land in the middle of a SysEx).
void sendChannel(Plugin* p, const uint8_t* m, int n) {
    const uint8_t link = p->link.load(std::memory_order_relaxed);
    if (link == kSeq) sendMessage(p, m, n);
    else if (link != kNone) p->toSend.push(m, n);
}

void trackNote(Plugin* p, int ch, int note, bool on) {
    std::atomic<uint8_t>& b = p->held[ch][note >> 3];
    const uint8_t bit = static_cast<uint8_t>(1u << (note & 7));
    if (on) b.fetch_or(bit, std::memory_order_relaxed);
    else b.fetch_and(static_cast<uint8_t>(~bit), std::memory_order_relaxed);
}

// Note-offs for what we hold, then sustain off and all-notes-off on the channel. direct: from the I/O thread (or once
// it has stopped), which sends itself instead of queueing (the queue has one producer, the audio thread).
void allNotesOff(Plugin* p, bool direct) {
    for (int ch = 0; ch < 16; ++ch) {
        bool any = false;
        for (int k = 0; k < 16; ++k) {
            uint8_t bits = p->held[ch][k].exchange(0, std::memory_order_relaxed);
            for (int b = 0; bits; ++b, bits >>= 1) {
                if (!(bits & 1)) continue;
                const uint8_t m[3] = {static_cast<uint8_t>(0x80 | ch), static_cast<uint8_t>(k * 8 + b), 0};
                if (direct) sendMessage(p, m, 3); else sendChannel(p, m, 3);
                any = true;
            }
        }
        if (any || ch == p->ctl[kMidiCh].load(std::memory_order_relaxed)) {
            const uint8_t sus[3] = {static_cast<uint8_t>(0xb0 | ch), 64, 0}, off[3] = {static_cast<uint8_t>(0xb0 | ch), 123, 0};
            if (direct) {
                sendMessage(p, sus, 3);
                sendMessage(p, off, 3);
            } else {
                sendChannel(p, sus, 3);
                sendChannel(p, off, 3);
            }
        }
    }
}

uint8_t checksum(const uint8_t* m, int from, int to) {  // sum of bytes from..to inclusive, 7 bits
    unsigned s = 0;
    for (int i = from; i <= to; ++i) s += m[i];
    return static_cast<uint8_t>(s & 0x7f);
}

int buildDump(Plugin* p, uint8_t bank, uint8_t program, uint8_t* m) {
    const uint8_t head[9] = {0xf0, 0x00, 0x20, 0x33, 0x01, kDeviceOmni, kDumpSingle, bank, program};
    std::memcpy(m, head, 9);
    for (int i = 0; i < 256; ++i) m[9 + i] = p->image[i].load(std::memory_order_relaxed) & 0x7f;
    m[265] = checksum(m, 5, 264);
    for (int i = 0; i < 256; ++i) m[266 + i] = p->image[256 + i].load(std::memory_order_relaxed) & 0x7f;
    m[522] = checksum(m, 5, 521);
    m[523] = 0xf7;
    return kDumpSize;
}

// ---- Pacing: what we send stays within what the TI's USB MIDI drains (a full buffer drops bytes) ------------------
bool spend(Plugin* p, int n) {
    const uint32_t now = nowMs();
    const uint32_t dt = now - p->lastPace;
    p->lastPace = now;
    p->tokens = p->tokens + static_cast<int>(dt > 1000 ? 1000 : dt) * kBytesPerMs;
    if (p->tokens > kBurst) p->tokens = kBurst;
    if (p->tokens < n && p->tokens < kBurst) return false;
    p->tokens -= n;
    return true;
}

// ---- Receiving -------------------------------------------------------------------------------------------------
void markHost(Plugin* p, int vst) { p->notify[vst].store(1, std::memory_order_relaxed); }

void applyByte(Plugin* p, uint8_t page, uint8_t index, uint8_t value, bool fromTi) {
    const int off = imageOffset(page);
    if (off >= 0) p->image[off + index].store(value & 0x7f, std::memory_order_relaxed);
    for (int i = 0; i < kNumVirus; ++i) {
        if (ti::kParams[i].page != page || ti::kParams[i].index != index) continue;
        p->raw[i].store(value & 0x7f, std::memory_order_relaxed);
        if (fromTi) markHost(p, kNumControls + i);
    }
}

void applyImage(Plugin* p, const uint8_t* bytes) {  // a whole Single into the plugin, every knob follows
    for (int i = 0; i < kImage; ++i) p->image[i].store(bytes[i] & 0x7f, std::memory_order_relaxed);
    for (int i = 0; i < kNumVirus; ++i) {
        const int off = imageOffset(ti::kParams[i].page);
        if (off < 0) continue;
        p->raw[i].store(bytes[off + ti::kParams[i].index] & 0x7f, std::memory_order_relaxed);
        markHost(p, kNumControls + i);
    }
    p->imageValid.store(true, std::memory_order_release);
    markHost(p, kPatch);
}

void onDump(Plugin* p, const uint8_t* m, int n) {
    // F0 00 20 33 01 dd 10 bank program [256] cs [256] cs F7 (TI), or [256] cs F7 (older Virus)
    const uint8_t bank = m[7], program = m[8];
    uint8_t bytes[kImage];
    for (int i = 0; i < kImage; ++i) bytes[i] = p->image[i].load(std::memory_order_relaxed);
    if (n == kDumpSize) {
        if (checksum(m, 5, 264) != m[265] || checksum(m, 5, 521) != m[522]) {
            if (p->await != kAwaitNothing) setStatus(p, kStBadDump);
            return;
        }
        std::memcpy(bytes, m + 9, 256);
        std::memcpy(bytes + 256, m + 266, 256);
    } else if (n == 9 + 256 + 2) {
        if (checksum(m, 5, 264) != m[265]) return;
        std::memcpy(bytes, m + 9, 256);
    } else {
        return;
    }
    if (p->await == kAwaitLoad && bank != 0) {
        applyImage(p, bytes);
        p->await = kAwaitNothing;
        p->wantSend.store(true, std::memory_order_relaxed);  // and into the edit buffer, so it plays
        setStatus(p, kStLoaded, bank - 1, program);
        return;
    }
    if (bank == 0 && program == targetPart(p)) {  // the edit buffer we edit (asked for, or sent by the TI)
        applyImage(p, bytes);
        if (p->await == kAwaitEdit) setStatus(p, kStReadOk);
        p->await = kAwaitNothing;
    }
}

void onSysex(Plugin* p, const uint8_t* m, int n) {
    if (n < 8 || m[1] != 0x00 || m[2] != 0x20 || m[3] != 0x33 || m[4] != 0x01) return;
    const uint8_t cmd = m[6];
    if (cmd == kDumpSingle && n >= 9) {
        onDump(p, m, n);
        return;
    }
    if (n != 11) return;
    const uint8_t page = cmd, part = m[7], index = m[8], value = m[9];
    if (page == kPageGlobal) {
        applyByte(p, page, index, value, true);
    } else if (imageOffset(page) >= 0 || page == kPageMulti) {
        const uint8_t t = targetPart(p);
        if (part == t || (t == kPartSingle && part == 0)) applyByte(p, page, index, value, true);
    }
}

void onChannel(Plugin* p, const uint8_t* m) {  // panel moves the TI reports as controllers / poly pressure
    if ((m[0] & 0x0f) != p->ctl[kMidiCh].load(std::memory_order_relaxed)) return;
    const uint8_t st = m[0] & 0xf0;
    if (st == 0xb0 && m[1] != 0 && m[1] != 32 && m[1] < 120) applyByte(p, kPageA, m[1], m[2], true);
    else if (st == 0xa0) applyByte(p, kPageB, m[1], m[2], true);
}

void feedByte(Plugin* p, uint8_t b) {  // the raw MIDI byte stream from the TI
    if (b >= 0xf8) return;  // real time
    if (b == 0xf0) {
        p->inSysex = true;
        p->rxLen = 0;
        p->rx[p->rxLen++] = b;
        return;
    }
    if (p->inSysex) {
        if (b == 0xf7) {
            if (p->rxLen < static_cast<int>(sizeof p->rx)) p->rx[p->rxLen++] = b;
            onSysex(p, p->rx, p->rxLen);
            p->inSysex = false;
        } else if (b & 0x80) {
            p->inSysex = false;  // aborted SysEx: the status byte starts something else
        } else if (p->rxLen < static_cast<int>(sizeof p->rx)) {
            p->rx[p->rxLen++] = b;
            return;
        } else {
            return;
        }
        if (b == 0xf7) return;
    }
    if (b & 0x80) {
        p->running = b;
        p->chanLen = 0;
        const uint8_t st = b & 0xf0;
        p->chanNeed = (st == 0xc0 || st == 0xd0) ? 1 : (b >= 0xf0 ? 0 : 2);
        return;
    }
    if (!p->running || p->chanNeed == 0) return;
    p->chan[p->chanLen++] = b;
    if (p->chanLen == p->chanNeed) {
        const uint8_t m[3] = {p->running, p->chan[0], p->chanLen > 1 ? p->chan[1] : static_cast<uint8_t>(0)};
        onChannel(p, m);
        p->chanLen = 0;
    }
}

void receive(Plugin* p) {
    const int fd = p->fd.load(std::memory_order_relaxed);
    const uint8_t link = p->link.load(std::memory_order_relaxed);
    if (fd < 0 || link == kRawSendOnly) return;
    uint8_t buf[4096];
    for (int rounds = 0; rounds < 16; ++rounds) {
        const ssize_t got = ::read(fd, buf, sizeof buf);
        if (got <= 0) return;
        if (link != kSeq) {
            for (ssize_t i = 0; i < got; ++i) feedByte(p, buf[i]);
            continue;
        }
        for (size_t at = 0; at + sizeof(seq::Event) <= static_cast<size_t>(got);) {
            seq::Event ev;
            std::memcpy(&ev, buf + at, sizeof ev);
            at += sizeof ev;
            size_t extra = 0;
            if ((ev.flags & seq::kLengthMask) == seq::kLengthVariable) extra = ev.data.ext.len;
            if (at + extra > static_cast<size_t>(got)) break;
            const uint8_t* data = buf + at;
            at += extra;
            switch (ev.type) {
                case seq::kSysex:
                    for (size_t i = 0; i < extra; ++i) feedByte(p, data[i]);
                    break;
                case seq::kController: {
                    const uint8_t m[3] = {static_cast<uint8_t>(0xb0 | (ev.data.control.channel & 15)),
                                          static_cast<uint8_t>(ev.data.control.param & 127),
                                          static_cast<uint8_t>(ev.data.control.value & 127)};
                    onChannel(p, m);
                    break;
                }
                case seq::kKeyPress: {
                    const uint8_t m[3] = {static_cast<uint8_t>(0xa0 | (ev.data.note.channel & 15)), ev.data.note.note,
                                          ev.data.note.velocity};
                    onChannel(p, m);
                    break;
                }
                default: break;
            }
        }
    }
}

// ---- Connecting ------------------------------------------------------------------------------------------------
bool containsVirus(const char* s) {
    for (; *s; ++s)
        if ((s[0] | 32) == 'v' && (s[1] | 32) == 'i' && (s[2] | 32) == 'r' && (s[3] | 32) == 'u' && (s[4] | 32) == 's') return true;
    return false;
}

bool readSmall(const char* path, char* out, size_t n) {
    const int f = ::open(path, O_RDONLY | O_CLOEXEC);
    if (f < 0) return false;
    const ssize_t got = ::read(f, out, n - 1);
    ::close(f);
    if (got <= 0) return false;
    out[got] = 0;
    return true;
}

// Whether an Access device is on USB, and its product ID: to tell "not plugged in" from "no driver".
bool findUsbVirus(int* product) {
    DIR* d = ::opendir("/sys/bus/usb/devices");
    if (!d) return false;
    bool found = false;
    while (dirent* e = ::readdir(d)) {
        if (e->d_name[0] == '.') continue;
        char path[300], v[16];
        std::snprintf(path, sizeof path, "/sys/bus/usb/devices/%s/idVendor", e->d_name);
        if (!readSmall(path, v, sizeof v) || std::strncmp(v, "133e", 4) != 0) continue;
        std::snprintf(path, sizeof path, "/sys/bus/usb/devices/%s/idProduct", e->d_name);
        *product = 0;
        if (readSmall(path, v, sizeof v))
            for (const char* c = v; hexDigit(*c) >= 0; ++c) *product = *product * 16 + hexDigit(*c);
        found = true;
        break;
    }
    ::closedir(d);
    return found;
}

// The ALSA card number of the TI, from /proc/asound/cards (" 2 [VirusTI ]: USB-Audio - Virus TI ...").
int findVirusCard() {
    char text[4096];
    if (!readSmall("/proc/asound/cards", text, sizeof text)) return -1;
    for (char* line = text; line && *line;) {
        char* next = std::strchr(line, '\n');
        if (next) *next++ = 0;
        const char* c = line;
        while (*c == ' ') ++c;
        if (*c >= '0' && *c <= '9' && containsVirus(line)) return parseInt(c);
        line = next;
    }
    return -1;
}

void disconnect(Plugin* p) {
    const int fd = p->fd.exchange(-1, std::memory_order_acq_rel);
    p->link.store(kNone, std::memory_order_release);
    if (fd >= 0 && fd != p->testFd) ::close(fd);
    if (p->ctlFd >= 0) ::close(p->ctlFd);
    p->ctlFd = -1;
    p->inSysex = false;
    p->running = 0;
    p->await = kAwaitNothing;
}

bool connectRaw(Plugin* p, int card) {
    char path[64];
    std::snprintf(path, sizeof path, "/dev/snd/controlC%d", card);
    p->ctlFd = ::open(path, O_RDWR | O_CLOEXEC);
    int sub = 1;  // the "Synth" port
    if (p->ctlFd >= 0) ::ioctl(p->ctlFd, seq::kCtlPreferRawmidiSubdevice, &sub);
    std::snprintf(path, sizeof path, "/dev/snd/midiC%dD0", card);
    int fd = ::open(path, O_RDWR | O_NONBLOCK | O_CLOEXEC);
    uint8_t link = kRaw;
    if (fd < 0 && errno == EBUSY) {
        fd = ::open(path, O_WRONLY | O_APPEND | O_NONBLOCK | O_CLOEXEC);
        link = kRawSendOnly;
    }
    if (fd < 0) {
        const bool busy = errno == EBUSY;
        if (p->ctlFd >= 0) ::close(p->ctlFd);
        p->ctlFd = -1;
        setStatus(p, busy ? kStBusy : kStNoDriver);
        return false;
    }
    p->link.store(link, std::memory_order_relaxed);
    p->fd.store(fd, std::memory_order_release);
    setStatus(p, link == kRaw ? kStConnectedRaw : kStConnectedSendOnly, card);
    return true;
}

bool connectSeq(Plugin* p, int* busy) {
    *busy = 0;
    const char* dev = std::getenv("SKTI_SEQ_DEV");
    const int fd = ::open(dev && *dev ? dev : "/dev/snd/seq", O_RDWR | O_NONBLOCK | O_CLOEXEC);
    if (fd < 0) return false;
    int me = -1;
    seq::ClientInfo ci;
    seq::PortInfo pi;
    std::memset(&ci, 0, sizeof ci);
    if (::ioctl(fd, seq::kClientId, &me) < 0 || me < 0) {
        ::close(fd);
        return false;
    }
    ci.client = me;
    if (::ioctl(fd, seq::kGetClientInfo, &ci) == 0) {
        std::snprintf(ci.name, sizeof ci.name, "%s", kName);
        ::ioctl(fd, seq::kSetClientInfo, &ci);
    }
    // Our port: no SUBS capabilities and not exported, so MPC doesn't pick it up as a MIDI device of its own
    // (it would then hear our notes again on its tracks).
    std::memset(&pi, 0, sizeof pi);
    pi.addr.client = static_cast<unsigned char>(me);
    std::snprintf(pi.name, sizeof pi.name, "Virus TI");
    pi.capability = seq::kCapRead | seq::kCapWrite | seq::kCapNoExport;
    pi.type = seq::kTypeMidiGeneric | seq::kTypeApplication;
    pi.midiChannels = 16;
    if (::ioctl(fd, seq::kCreatePort, &pi) < 0) {
        ::close(fd);
        return false;
    }
    const unsigned char myPort = pi.addr.port;
    // The TI: a client whose name says Virus, its "Synth" port (else its second port, else its first).
    int virus = -1, synth = -1, midi = -1;
    std::memset(&ci, 0, sizeof ci);
    ci.client = -1;
    while (virus < 0 && ::ioctl(fd, seq::kQueryNextClient, &ci) == 0) {
        if (!containsVirus(ci.name)) continue;
        seq::PortInfo q;
        std::memset(&q, 0, sizeof q);
        q.addr.client = static_cast<unsigned char>(ci.client);
        q.addr.port = 255;  // -1: from the first port
        int n = 0, first = -1, second = -1;
        while (::ioctl(fd, seq::kQueryNextPort, &q) == 0) {
            if (!(q.capability & seq::kCapWrite)) continue;
            const size_t len = std::strlen(q.name);
            if (len >= 5 && !std::strcmp(q.name + len - 5, "Synth")) synth = q.addr.port;
            if (n == 0) first = q.addr.port;
            if (n == 1) second = q.addr.port;
            ++n;
        }
        if (first >= 0) {
            virus = ci.client;
            if (synth < 0) synth = second >= 0 ? second : first;
            midi = first != synth ? first : -1;
        }
    }
    if (virus < 0) {
        ::close(fd);
        return false;
    }
    // Output first: the kernel opens the TI's MIDI device for it, and refuses (EBUSY) if another program holds it.
    seq::Subscribe s;
    std::memset(&s, 0, sizeof s);
    s.sender.client = static_cast<unsigned char>(me);
    s.sender.port = myPort;
    s.dest.client = static_cast<unsigned char>(virus);
    s.dest.port = static_cast<unsigned char>(synth);
    if (::ioctl(fd, seq::kSubscribe, &s) < 0) {
        *busy = 1;
        ::close(fd);
        return false;
    }
    // Input: the synth's port and the MIDI port (the TI reports panel changes on one of them).
    p->numVirusPorts = 0;
    const int inPorts[2] = {synth, midi};
    for (int port : inPorts) {
        if (port < 0) continue;
        seq::Subscribe in;
        std::memset(&in, 0, sizeof in);
        in.sender.client = static_cast<unsigned char>(virus);
        in.sender.port = static_cast<unsigned char>(port);
        in.dest.client = static_cast<unsigned char>(me);
        in.dest.port = myPort;
        if (::ioctl(fd, seq::kSubscribe, &in) == 0) p->virusPorts[p->numVirusPorts++] = static_cast<uint8_t>(port);
    }
    p->virusClient = static_cast<uint8_t>(virus);
    p->myClient.store(static_cast<uint8_t>(me), std::memory_order_relaxed);
    p->myPort.store(myPort, std::memory_order_relaxed);
    p->link.store(kSeq, std::memory_order_relaxed);
    p->fd.store(fd, std::memory_order_release);
    setStatus(p, kStConnectedSeq, virus, synth);
    return true;
}

bool seqAlive(Plugin* p) {  // the TI's client is still there (unplugged: the kernel removes it)
    const int fd = p->fd.load(std::memory_order_relaxed);
    seq::ClientInfo ci;
    std::memset(&ci, 0, sizeof ci);
    ci.client = p->virusClient;
    return ::ioctl(fd, seq::kGetClientInfo, &ci) == 0 && containsVirus(ci.name);
}

bool rawAlive(Plugin* p) {  // a raw MIDI device of an unplugged card reports an error
    pollfd q = {p->fd.load(std::memory_order_relaxed), 0, 0};
    return ::poll(&q, 1, 0) >= 0 && !(q.revents & (POLLERR | POLLHUP | POLLNVAL));
}

void tryConnect(Plugin* p) {
    if (p->testFd >= 0) {
        p->link.store(kTestFd, std::memory_order_relaxed);
        p->fd.store(p->testFd, std::memory_order_release);
        setStatus(p, kStTest);
        return;
    }
    int busy = 0;
    if (connectSeq(p, &busy)) return;
    const int card = findVirusCard();
    if (card >= 0 && connectRaw(p, card)) return;
    if (card >= 0) return;  // connectRaw said why
    int product = 0;
    if (findUsbVirus(&product)) setStatus(p, kStNoDriver, product >> 8, product & 0xff);
    else if (busy) setStatus(p, kStBusy);
    else setStatus(p, kStNoUsb);
}

// ---- The I/O thread ------------------------------------------------------------------------------------------
bool takeDirty(Plugin* p, int* index) {
    for (int w = 0; w < (kNumVirus + 31) / 32; ++w) {
        uint32_t bits = p->dirty[w].load(std::memory_order_relaxed);
        while (bits) {
            const int b = __builtin_ctz(bits);
            const uint32_t mask = 1u << b;
            if (p->dirty[w].fetch_and(~mask, std::memory_order_acq_rel) & mask) {
                *index = w * 32 + b;
                return true;
            }
            bits &= ~mask;
        }
    }
    return false;
}

void markDirty(Plugin* p, int i) { p->dirty[i / 32].fetch_or(1u << (i % 32), std::memory_order_release); }

void markAllSingleDirty(Plugin* p) {
    for (int i = 0; i < kNumVirus; ++i)
        if (imageOffset(ti::kParams[i].page) >= 0) markDirty(p, i);
}

void sendParam(Plugin* p, int i) {
    const ti::Param& t = ti::kParams[i];
    const uint8_t v = clampRaw(meaning(p, i), rawOf(p, i));
    const uint8_t part = t.page == kPageGlobal ? 0 : targetPart(p);
    const uint8_t m[11] = {0xf0, 0x00, 0x20, 0x33, 0x01, kDeviceOmni, t.page, part, t.index, v, 0xf7};
    if (!sendMessage(p, m, 11)) markDirty(p, i);  // try again next round
}

void pump(Plugin* p) {
    const uint32_t now = nowMs();
    const uint8_t link = p->link.load(std::memory_order_relaxed);
    if (link == kNone) {
        if (now - p->lastTry >= kRetryMs) {
            p->lastTry = now;
            tryConnect(p);
        }
        return;
    }
    if (now - p->lastAlive >= kAliveMs) {
        p->lastAlive = now;
        const bool alive = link == kSeq ? seqAlive(p) : link == kTestFd ? true : rawAlive(p);
        if (!alive) {
            disconnect(p);
            setStatus(p, kStLost);
            p->lastTry = now;
            return;
        }
    }
    receive(p);
    // channel messages queued by the audio thread (raw links): whole messages only
    while (p->toSend.size() > 0) {
        const uint8_t st = p->toSend.peek(0);
        const int n = ((st & 0xf0) == 0xc0 || (st & 0xf0) == 0xd0) ? 2 : 3;
        if (p->toSend.size() < n) break;
        uint8_t m[3];
        for (int i = 0; i < n; ++i) m[i] = p->toSend.peek(i);
        sendMessage(p, m, n);
        p->toSend.drop(n);
        p->tokens -= n;
    }
    if (p->wantPanic.exchange(false, std::memory_order_relaxed)) {
        allNotesOff(p, true);
        setStatus(p, kStPanic);
    }
    if (p->await != kAwaitNothing && now - p->awaitSince > kAnswerMs) {
        p->await = kAwaitNothing;
        setStatus(p, kStNoAnswer);
    }
    uint8_t m[kDumpSize];
    if (p->wantRead.load(std::memory_order_relaxed) && spend(p, 10)) {
        p->wantRead.store(false, std::memory_order_relaxed);
        const uint8_t r[10] = {0xf0, 0x00, 0x20, 0x33, 0x01, kDeviceOmni, kRequestSingle, 0, targetPart(p), 0xf7};
        if (sendMessage(p, r, 10)) {
            p->await = kAwaitEdit;
            p->awaitSince = now;
            setStatus(p, kStReading);
        }
    }
    if (p->wantLoad.load(std::memory_order_relaxed) && spend(p, 10)) {
        p->wantLoad.store(false, std::memory_order_relaxed);
        const uint8_t bank = p->ctl[kBank].load(std::memory_order_relaxed), prog = p->ctl[kProgram].load(std::memory_order_relaxed);
        const uint8_t r[10] = {0xf0, 0x00, 0x20, 0x33, 0x01, kDeviceOmni, kRequestSingle, static_cast<uint8_t>(bank + 1), prog, 0xf7};
        if (sendMessage(p, r, 10)) {
            p->await = kAwaitLoad;
            p->awaitSince = now;
            setStatus(p, kStLoading, bank, prog);
        }
    }
    const bool autoSend = p->pendingAutoSend.load(std::memory_order_acquire);
    if ((p->wantSend.load(std::memory_order_relaxed) || autoSend) && (!p->imageValid.load(std::memory_order_acquire) || spend(p, kDumpSize))) {
        p->wantSend.store(false, std::memory_order_relaxed);
        p->pendingAutoSend.store(false, std::memory_order_relaxed);
        if (p->imageValid.load(std::memory_order_acquire)) {
            const int n = buildDump(p, 0, targetPart(p), m);
            if (sendMessage(p, m, n)) {
                // the dump carries every parameter: what is still marked would only repeat it
                for (int w = 0; w < (kNumVirus + 31) / 32; ++w) {
                    uint32_t keep = 0;
                    for (int b = 0; b < 32 && w * 32 + b < kNumVirus; ++b)
                        if (imageOffset(ti::kParams[w * 32 + b].page) < 0) keep |= 1u << b;
                    p->dirty[w].fetch_and(keep, std::memory_order_relaxed);
                }
                p->holdParamsUntil = now + kAfterDumpMs;
                if (p->status.load(std::memory_order_relaxed) != kStLoaded) setStatus(p, kStSent);
            }
        } else {
            markAllSingleDirty(p);  // no real patch header yet: every parameter one by one
            setStatus(p, kStSentParams);
        }
    }
    if (p->wantStore.load(std::memory_order_relaxed) && spend(p, kDumpSize)) {
        p->wantStore.store(false, std::memory_order_relaxed);
        const uint8_t bank = p->ctl[kBank].load(std::memory_order_relaxed), prog = p->ctl[kProgram].load(std::memory_order_relaxed);
        const int n = buildDump(p, static_cast<uint8_t>(bank + 1), prog, m);
        if (sendMessage(p, m, n)) {
            p->holdParamsUntil = now + kAfterDumpMs;
            setStatus(p, kStStored, bank, prog);
        }
    }
    // parameter changes: after a dump, the TI drops changes that arrive while it takes the patch
    if (static_cast<int32_t>(now - p->holdParamsUntil) >= 0) {
        int i;
        while (takeDirty(p, &i)) {
            if (!spend(p, 11)) {
                markDirty(p, i);
                break;
            }
            sendParam(p, i);
        }
    }
}

void* ioThread(void* arg) {
    Plugin* p = static_cast<Plugin*>(arg);
    p->lastPace = nowMs();
    p->tokens = kBurst;
    p->lastTry = nowMs() - kRetryMs;
    while (!p->quit.load(std::memory_order_acquire)) {
        pump(p);
        const int fd = p->fd.load(std::memory_order_relaxed);
        pollfd q = {fd, POLLIN, 0};
        if (fd >= 0 && p->link.load(std::memory_order_relaxed) != kRawSendOnly) ::poll(&q, 1, 3);
        else {
            timespec ts = {0, 3000000};
            ::nanosleep(&ts, nullptr);
        }
    }
    return nullptr;
}

// ---- Host side: parameters -------------------------------------------------------------------------------------
int tickFrom(float n, float base) {  // a Q-Link or wheel tick moves 1/128 of the range (see SK Filterbank)
    if (base < 0.f) return 0;
    const float d = (n - base) * 128.f;
    const float k = std::round(d);
    if (k == 0.f || std::fabs(k) > 4.f || std::fabs(d - k) > 0.004f) return 0;
    return k > 0.f ? 1 : -1;
}

int settleOption(float n, int current, float lastSent, int count) {  // option index for a host value
    const float last = static_cast<float>(count - 1);
    const float pos = n * last;
    const float nearest = std::round(pos);
    if (std::fabs(pos - nearest) <= 0.001f) return static_cast<int>(nearest);
    int step = tickFrom(n, static_cast<float>(current) / last);
    if (!step) step = tickFrom(n, lastSent);
    if (!step) {
        if (std::fabs(pos - static_cast<float>(current)) >= 1.f) return static_cast<int>(nearest);
        step = pos > static_cast<float>(current) ? 1 : -1;
    }
    const int idx = current + step;
    return idx < 0 ? 0 : idx > count - 1 ? count - 1 : idx;
}

void setVirus(Plugin* p, int i, uint8_t v) {
    const ti::Param& t = ti::kParams[i];
    if (rawOf(p, i) == v) return;
    p->raw[i].store(v, std::memory_order_relaxed);
    const int off = imageOffset(t.page);
    if (off >= 0) p->image[off + t.index].store(v, std::memory_order_relaxed);
    markDirty(p, i);
}

void pressButton(Plugin* p, int i) {
    auto step = [p](int c, int d, int count) {
        int v = p->ctl[c].load(std::memory_order_relaxed) + d;
        v = v < 0 ? 0 : v >= count ? count - 1 : v;
        p->ctl[c].store(static_cast<uint8_t>(v), std::memory_order_relaxed);
        markHost(p, c);
        p->storeArmed.store(false, std::memory_order_relaxed);
    };
    switch (i) {
        case kRead: p->wantRead.store(true, std::memory_order_relaxed); break;
        case kSend: p->wantSend.store(true, std::memory_order_relaxed); break;
        case kLoad: p->wantLoad.store(true, std::memory_order_relaxed); break;
        case kPanic: p->wantPanic.store(true, std::memory_order_relaxed); break;
        case kStore: {
            const uint32_t now = nowMs();
            if (p->storeArmed.load(std::memory_order_relaxed) &&
                now - p->storeArmedMs.load(std::memory_order_relaxed) < kStoreArmMs) {
                p->storeArmed.store(false, std::memory_order_relaxed);
                p->wantStore.store(true, std::memory_order_relaxed);
            } else {
                p->storeArmed.store(true, std::memory_order_relaxed);
                p->storeArmedMs.store(now, std::memory_order_relaxed);
                setStatus(p, kStStoreArmed, p->ctl[kBank].load(std::memory_order_relaxed),
                          p->ctl[kProgram].load(std::memory_order_relaxed));
            }
            break;
        }
        case kBankPrev: step(kBank, -1, 32); break;
        case kBankNext: step(kBank, 1, 32); break;
        case kProgPrev: step(kProgram, -1, 128); break;
        case kProgNext: step(kProgram, 1, 128); break;
        default: break;
    }
}

void setParameter(AEffect* e, int32_t i, float v) {
    if (i < 0 || i >= kNumVst) return;
    Plugin* p = self(e);
    const float n = v >= 0.f ? (v <= 1.f ? v : 1.f) : 0.f;  // NaN too
    const float lastSent = p->sent[i].exchange(n, std::memory_order_relaxed);
    if (i >= kNumControls) {
        const int k = i - kNumControls;
        const ti::Param& t = ti::kParams[k];
        const int count = t.rawMax + 1;
        const int cur = rawOf(p, k);
        // Fewer than 128 steps: a Q-Link tick is one step (rounding alone would leave it where it was).
        const int raw = count < 128 ? settleOption(n, cur, lastSent, count) : static_cast<int>(std::lround(n * t.rawMax));
        setVirus(p, k, static_cast<uint8_t>(raw));
        return;
    }
    const Control& c = kControls[i];
    switch (c.kind) {
        case kReadout: break;  // also takes MPC's parameter-0 nudges harmlessly
        case kOption:
        case kStepper: {
            const int cur = p->ctl[i].load(std::memory_order_relaxed);
            const int nv = settleOption(n, cur, lastSent, c.count);
            if (nv != cur) {
                if (i == kMidiCh) p->wantPanic.store(true, std::memory_order_relaxed);  // notes held on the old channel
                p->ctl[i].store(static_cast<uint8_t>(nv), std::memory_order_relaxed);
                if (i == kPart) markHost(p, kPatch);
                if (i == kBank || i == kProgram) p->storeArmed.store(false, std::memory_order_relaxed);
            }
            break;
        }
        case kButton:
            if (n > 0.5f && p->pressed[i].load(std::memory_order_relaxed) < 0.5f) {
                const uint32_t ms = nowMs(), fr = p->frames.load(std::memory_order_relaxed);
                const bool repeat = fr - p->pressFrame[i].load(std::memory_order_relaxed) < kDebounceFrames &&
                                    ms - p->pressMs[i].load(std::memory_order_relaxed) < kDebounceMs;
                p->pressed[i].store(1.f, std::memory_order_relaxed);
                p->holdFrames[i].store(kHoldFrames, std::memory_order_relaxed);
                if (!repeat) {
                    p->pressFrame[i].store(fr, std::memory_order_relaxed);
                    p->pressMs[i].store(ms, std::memory_order_relaxed);
                    pressButton(p, i);
                }
            } else if (n <= 0.5f) {
                p->pressed[i].store(0.f, std::memory_order_relaxed);
            }
            break;
    }
}

float getParameter(AEffect* e, int32_t i) {
    if (i < 0 || i >= kNumVst) return 0.f;
    Plugin* p = self(e);
    if (i >= kNumControls) {
        const int k = i - kNumControls;
        return static_cast<float>(rawOf(p, k)) / static_cast<float>(ti::kParams[k].rawMax ? ti::kParams[k].rawMax : 1);
    }
    const Control& c = kControls[i];
    switch (c.kind) {
        case kOption:
        case kStepper: return static_cast<float>(p->ctl[i].load(std::memory_order_relaxed)) / static_cast<float>(c.count - 1);
        case kButton: return p->pressed[i].load(std::memory_order_relaxed);
        default: return 0.f;
    }
}

void paramName(Plugin* p, int i, char* out, size_t len) {
    if (i >= kNumControls) std::snprintf(out, len, "%s", meaning(p, i - kNumControls).shortName);
    else std::snprintf(out, len, "%s", kControls[i].name);
}

void displayText(Plugin* p, int i, char* out, size_t len) {
    out[0] = 0;
    if (i >= kNumControls) {
        valueText(p, i - kNumControls, out, len);
        return;
    }
    const int v = p->ctl[i].load(std::memory_order_relaxed);
    switch (i) {
        case kStatus: statusText(p, out, len); break;
        case kPart: if (v == 0) std::snprintf(out, len, "Single"); else std::snprintf(out, len, "Part %d", v); break;
        case kMidiCh: std::snprintf(out, len, "Ch %d", v + 1); break;
        case kNotes:
        case kAutoSend: std::snprintf(out, len, "%s", v ? "On" : "Off"); break;
        case kBank: bankName(v, out, len); break;
        case kProgram: std::snprintf(out, len, "Program %03d", v + 1); break;
        case kPatch: {
            char name[16];
            patchName(p, name);
            const int part = p->ctl[kPart].load(std::memory_order_relaxed);
            char where[16];
            if (part) std::snprintf(where, sizeof where, "Part %d", part);
            else std::snprintf(where, sizeof where, "Single");
            if (p->imageValid.load(std::memory_order_relaxed))
                std::snprintf(out, len, "%s: \"%s\"", where, name);
            else
                std::snprintf(out, len, "%s: not read from the Virus yet (READ, or LOAD a program)", where);
            break;
        }
        default: break;
    }
}

// Tell the host what changed on our side, from process (never from inside a host call): buttons springing back,
// knobs the TI moved, a few per block. The display update (names and readouts) waits until those are out.
void notifyHost(Plugin* p, int32_t frames) {
    if (!p->master) return;
    for (int i = 0; i < kNumControls; ++i) {
        if (p->holdFrames[i].load(std::memory_order_relaxed) > 0 &&
            p->holdFrames[i].fetch_sub(frames, std::memory_order_relaxed) <= frames) {
            p->holdFrames[i].store(0, std::memory_order_relaxed);
            p->pressed[i].store(0.f, std::memory_order_relaxed);
            p->master(&p->fx, audioMasterAutomate, i, 0, nullptr, 0.f);
        }
    }
    int sent = 0;
    for (int i = 0; i < kNumVst; ++i) {
        if (!p->notify[i].load(std::memory_order_relaxed)) continue;
        if (sent == kMaxNotify) return;
        if (!p->notify[i].exchange(0, std::memory_order_relaxed)) continue;
        if (i == kPatch || i == kStatus) {
            p->updateDisplay.store(true, std::memory_order_relaxed);
            continue;
        }
        p->master(&p->fx, audioMasterAutomate, i, 0, nullptr, getParameter(&p->fx, i));
        ++sent;
    }
    const uint32_t sig = nameSignature(p);
    if (sig != p->nameSig.load(std::memory_order_relaxed)) {
        p->nameSig.store(sig, std::memory_order_relaxed);
        p->updateDisplay.store(true, std::memory_order_relaxed);
    }
    if (p->updateDisplay.exchange(false, std::memory_order_relaxed))
        p->master(&p->fx, audioMasterUpdateDisplay, 0, 0, nullptr, 0.f);
}

void processEvents(Plugin* p, const VstEvents* ev) {
    if (!ev) return;
    const bool notes = p->ctl[kNotes].load(std::memory_order_relaxed) != 0;
    const uint8_t ch = p->ctl[kMidiCh].load(std::memory_order_relaxed);
    for (int32_t k = 0; k < ev->numEvents; ++k) {
        const VstEvent* e = ev->events[k];
        if (!e || e->type != kVstMidiType || !notes) continue;
        const VstMidiEvent* me = reinterpret_cast<const VstMidiEvent*>(e);
        uint8_t m[3] = {me->midiData[0], static_cast<uint8_t>(me->midiData[1] & 0x7f), static_cast<uint8_t>(me->midiData[2] & 0x7f)};
        const uint8_t st = m[0] & 0xf0;
        if (st < 0x80 || st == 0xf0) continue;
        // MPC hands a plugin note-ons on channel 1 whatever channel the track used: the plugin's channel decides.
        m[0] = static_cast<uint8_t>(st | ch);
        if (st == 0x90 || st == 0x80) trackNote(p, ch, m[1], st == 0x90 && m[2] > 0);
        sendChannel(p, m, (st == 0xc0 || st == 0xd0) ? 2 : 3);
    }
}

void run(AEffect* e, float** out, int32_t n, bool accumulate) {
    Plugin* p = self(e);
    if (out && n > 0 && !accumulate) {
        for (int c = 0; c < 2; ++c)
            if (out[c]) std::memset(out[c], 0, sizeof(float) * static_cast<size_t>(n));
    }
    p->frames.store(p->frames.load(std::memory_order_relaxed) + static_cast<uint32_t>(n > 0 ? n : 0), std::memory_order_relaxed);
    notifyHost(p, n);
}
void processReplacing(AEffect* e, float**, float** out, int32_t n) { run(e, out, n, false); }
void processAccumulating(AEffect* e, float**, float** out, int32_t n) { run(e, out, n, true); }

// ---- State: "SKTI1;part=0;ch=0;notes=1;auto=1;bank=0;prog=0;valid=1;img=<1024 hex>;x.<key>=<v>...;end" -------
size_t serialize(Plugin* p, char* out, size_t cap) {
    size_t pos = static_cast<size_t>(std::snprintf(out, cap, "%s;part=%d;ch=%d;notes=%d;auto=%d;bank=%d;prog=%d;valid=%d;img=",
        kChunkMagic, p->ctl[kPart].load(), p->ctl[kMidiCh].load(), p->ctl[kNotes].load(), p->ctl[kAutoSend].load(),
        p->ctl[kBank].load(), p->ctl[kProgram].load(), p->imageValid.load() ? 1 : 0));
    static const char hex[] = "0123456789abcdef";
    for (int i = 0; i < kImage && pos + 2 < cap; ++i) {
        const uint8_t b = p->image[i].load(std::memory_order_relaxed);
        out[pos++] = hex[b >> 4];
        out[pos++] = hex[b & 15];
    }
    for (int i = 0; i < kNumVirus && pos < cap; ++i) {
        if (imageOffset(ti::kParams[i].page) >= 0) continue;
        pos += static_cast<size_t>(std::snprintf(out + pos, cap - pos, ";x.%s=%d", ti::kParams[i].key, rawOf(p, i)));
    }
    if (pos < cap) pos += static_cast<size_t>(std::snprintf(out + pos, cap - pos, ";end"));  // a cut-off state is refused
    if (pos >= cap) return 0;
    return pos;
}


bool deserialize(Plugin* p, const char* text, size_t size) {
    static char buf[8192];  // UI thread only
    const size_t n = size < sizeof buf - 1 ? size : sizeof buf - 1;
    std::memcpy(buf, text, n);
    buf[n] = 0;
    const size_t magic = std::strlen(kChunkMagic);
    if (std::strncmp(buf, kChunkMagic, magic) != 0 || (buf[magic] != ';' && buf[magic] != 0)) return false;
    uint8_t img[kImage];
    bool haveImg = false, complete = false;
    int valid = 0;
    uint8_t ctl[kNumControls] = {};
    ctl[kNotes] = 1;
    ctl[kAutoSend] = 1;
    uint8_t extra[kNumVirus];
    bool haveExtra[kNumVirus] = {};
    for (char* tok = std::strchr(buf, ';'); tok;) {
        char* next = std::strchr(tok + 1, ';');
        if (next) *next = 0;
        char* eq = std::strchr(tok + 1, '=');
        if (eq) {
            *eq = 0;
            const char* k = tok + 1;
            const char* v = eq + 1;
            const int iv = parseInt(v);
            if (!std::strcmp(k, "part")) ctl[kPart] = static_cast<uint8_t>(iv < 17 ? iv : 0);
            else if (!std::strcmp(k, "ch")) ctl[kMidiCh] = static_cast<uint8_t>(iv < 16 ? iv : 0);
            else if (!std::strcmp(k, "notes")) ctl[kNotes] = iv ? 1 : 0;
            else if (!std::strcmp(k, "auto")) ctl[kAutoSend] = iv ? 1 : 0;
            else if (!std::strcmp(k, "bank")) ctl[kBank] = static_cast<uint8_t>(iv < 32 ? iv : 0);
            else if (!std::strcmp(k, "prog")) ctl[kProgram] = static_cast<uint8_t>(iv < 128 ? iv : 0);
            else if (!std::strcmp(k, "valid")) valid = iv ? 1 : 0;
            else if (!std::strcmp(k, "img") && std::strlen(v) == 2 * kImage) {
                haveImg = true;
                for (int i = 0; i < kImage; ++i) {
                    const int hi = hexDigit(v[2 * i]), lo = hexDigit(v[2 * i + 1]);
                    if (hi < 0 || lo < 0) { haveImg = false; break; }
                    img[i] = static_cast<uint8_t>((hi << 4 | lo) & 0x7f);
                }
            } else if (k[0] == 'x' && k[1] == '.') {
                for (int i = 0; i < kNumVirus; ++i)
                    if (!std::strcmp(k + 2, ti::kParams[i].key)) {
                        extra[i] = static_cast<uint8_t>(iv & 0x7f);
                        haveExtra[i] = true;
                    }
            }
        }
        else if (!std::strcmp(tok + 1, "end")) complete = true;
        tok = next;
    }
    if (!haveImg || !complete) return false;
    for (int i = 0; i < kNumControls; ++i) {
        if (kControls[i].kind == kOption || kControls[i].kind == kStepper) p->ctl[i].store(ctl[i], std::memory_order_relaxed);
        markHost(p, i);
    }
    for (int i = 0; i < kImage; ++i) p->image[i].store(img[i], std::memory_order_relaxed);
    for (int i = 0; i < kNumVirus; ++i) {
        const int off = imageOffset(ti::kParams[i].page);
        if (off >= 0) p->raw[i].store(img[off + ti::kParams[i].index], std::memory_order_relaxed);
        else if (haveExtra[i]) p->raw[i].store(extra[i], std::memory_order_relaxed);
        markHost(p, kNumControls + i);
    }
    p->imageValid.store(valid != 0, std::memory_order_relaxed);
    for (int w = 0; w < (kNumVirus + 31) / 32; ++w) p->dirty[w].store(0, std::memory_order_relaxed);
    // The project's sound goes to the TI (now, or once it is connected); its global settings stay the TI's own.
    if (ctl[kAutoSend]) p->pendingAutoSend.store(true, std::memory_order_release);
    p->updateDisplay.store(true, std::memory_order_relaxed);
    return true;
}

// ---- Dispatcher ----------------------------------------------------------------------------------------------
void destroy(Plugin* p) {
    if (p->threadStarted) {
        p->quit.store(true, std::memory_order_release);
        pthread_join(p->thread, nullptr);
    }
    if (p->link.load() != kNone) allNotesOff(p, true);  // nothing left hanging on the TI
    disconnect(p);
    if (p->testFd >= 0) ::close(p->testFd);
    std::free(p);
}

intptr_t dispatcher(AEffect* e, int32_t op, int32_t idx, intptr_t v, void* ptr, float opt) {
    Plugin* p = self(e);
    (void)opt;
    switch (op) {
        case effOpen: return 1;
        case effClose: destroy(p); return 1;
        case effGetPlugCategory: return kPlugCategSynth;
        case effGetEffectName:
        case effGetProductString: copyStr(ptr, kName, 32); return 1;
        case effGetVendorString: copyStr(ptr, kVendor, 32); return 1;
        case effGetVendorVersion: return kVersion;
        case effGetVstVersion: return 2400;
        case effCanBeAutomated: return idx >= kNumControls && idx < kNumVst;
        case effGetParamName: {
            if (idx < 0 || idx >= kNumVst || !ptr) return 0;
            char buf[64];
            paramName(p, idx, buf, sizeof buf);
            copyStr(ptr, buf, 24);
            return 1;
        }
        case effGetParamLabel: copyStr(ptr, "", 8); return 1;
        case effGetParamDisplay: {
            if (idx < 0 || idx >= kNumVst || !ptr) return 0;
            char buf[128];
            displayText(p, idx, buf, sizeof buf);
            copyStr(ptr, buf, (idx == kStatus || idx == kPatch) ? 96 : 24);
            return 1;
        }
        case effSetProgram: return 0;
        case effGetProgram: return 0;
        case effSetProgramName: return 0;
        case effGetProgramName:
        case effGetProgramNameIndexed: {
            if (!ptr || idx > 0) return 0;
            char name[16];
            patchName(p, name);
            copyStr(ptr, name[0] ? name : "Virus TI", 24);
            return 1;
        }
        case effSetSampleRate: return 1;
        case effSetBlockSize: return 1;
        case effMainsChanged:
            if (!v) p->wantPanic.store(true, std::memory_order_relaxed);  // stopped: nothing left hanging on the TI
            return 1;
        case effProcessEvents: processEvents(p, static_cast<const VstEvents*>(ptr)); return 1;
        case effGetChunk: {
            if (!ptr) return 0;
            const size_t len = serialize(p, p->chunk, sizeof p->chunk);
            if (!len) return 0;
            *static_cast<void**>(ptr) = p->chunk;
            return static_cast<intptr_t>(len + 1);
        }
        case effSetChunk:
            return ptr && v > 0 && deserialize(p, static_cast<const char*>(ptr), static_cast<size_t>(v)) ? 1 : 0;
        case effCanDo: {
            const char* s = static_cast<const char*>(ptr);
            if (!s) return -1;
            return (!std::strcmp(s, "receiveVstEvents") || !std::strcmp(s, "receiveVstMidiEvent")) ? 1 : -1;
        }
        case effGetTailSize: return 1;
        default: return 0;
    }
}

